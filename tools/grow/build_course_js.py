#!/usr/bin/env python3
"""Rebuild js/<course>.js for ONE fact course from its entries files, leaving every other data file alone.

  python3 tools/grow/build_course_js.py earth

tools/build_extras.py rewrites every data file in one go (and is not idempotent for the others), so growing
a single course goes through this instead. Same gate as build_extras: shape, categories, kinds, 60 words,
editorial tripwires, the history year rule.
"""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import build_extras as B                                      # noqa: E402

CONST = {'body': 'BODY', 'earth': 'EARTH', 'astro': 'ASTRO', 'physical': 'PHYSICAL', 'micro': 'MICRO', 'ancient': 'ANCIENT',
         'america': 'AMERICA', 'utah': 'UTAH', 'world': 'WORLD', 'economics': 'ECONOMICS'}
NAMES = {'body': 'Body', 'earth': 'Earth', 'astro': 'Astronomy', 'physical': 'Physical science', 'micro': 'Microbiology',
         'ancient': 'Ancient history', 'america': 'American history', 'utah': 'Utah history',
         'world': 'World history', 'economics': 'Economics'}


def sections_of(course):
    """Section ids from schema.js, in the order the app shows them."""
    s = open(os.path.join(ROOT, 'js', 'schema.js'), encoding='utf-8').read()
    var = {'earth': 'EARTH_SECTIONS', 'astro': 'ASTRO_SECTIONS', 'physical': 'PHYSICAL_SECTIONS',
           'micro': 'MICRO_SECTIONS', 'ancient': 'ANCIENT_SECTIONS', 'america': 'AMERICA_SECTIONS',
           'utah': 'UTAH_SECTIONS', 'world': 'WORLD_SECTIONS', 'economics': 'ECONOMICS_SECTIONS',
           'body': 'BODY_SECTIONS'}[course]
    m = re.search(r'const %s = \{(.*?)\n\};' % var, s, re.S)
    return re.findall(r'^\s*(\w+)\s*:\s*\{', m.group(1), re.M)


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in CONST:
        raise SystemExit('usage: build_course_js.py <%s>' % '|'.join(CONST))
    c = sys.argv[1]
    order = sections_of(c)
    is_hist = c in ('ancient', 'america', 'utah', 'world')
    rows, problems = [], []
    if c == 'body':
        # The body ids (b1..b164) are referenced by the Try It Now tracker and are never renumbered, so the
        # shipped rows are the base and only the grown entries file is added to them.
        cur = open(os.path.join(ROOT, 'js', 'body.js'), encoding='utf-8').read()
        rows = [r for r in json.loads(re.search(r'const BODY = (\[.*\]);', cur, re.S).group(1))
                if not re.match(r'^[a-z]+-\d+$', r.get('id', ''))]
        for f in sorted(glob.glob(os.path.join(ROOT, '.work', 'entries-body-g*.json'))):
            rows += json.load(open(f, encoding='utf-8'))
    else:
        for f in sorted(glob.glob(os.path.join(ROOT, '.work', 'entries-%s-*.json' % c))):
            rows += json.load(open(f, encoding='utf-8'))
    good = []
    for e in rows:
        pr = B.check_history(e, set(order), c) if is_hist else B.check_flat(e, set(order), c)
        problems += pr
        if not any('EDITORIAL' in x or 'empty text' in x or 'unknown' in x for x in pr):
            good.append(e)
    ids = [e['id'] for e in good]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        problems.append('duplicate ids: ' + ', '.join(dup))
    pos = {id(e): i for i, e in enumerate(good)}
    good.sort(key=lambda e: (order.index(e['section']) if e['section'] in order else 999, pos[id(e)]))
    n = B.write_js(os.path.join(ROOT, 'js', c + '.js'), CONST[c], good,
                   '// Wonder Lab %s data. Generated by tools/build_extras.py and tools/grow/build_course_js.py\n' % NAMES[c].lower()
                   + ('// ids are stable and referenced by the Try It Now tracker — never renumber an existing one.\n' if c == 'body' else '')
                   + ('// Years are never `found` — see check_history and .work/BRIEF-ancient.md.\n' if is_hist else '')
                   + '// %d facts across %d sections.\n' % (len(good), len({e['section'] for e in good})))
    print('wrote %d %s facts -> js/%s.js (%d KB)' % (len(good), NAMES[c].lower(), c, n // 1024))
    for p in problems:
        print('  PROBLEM', p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
