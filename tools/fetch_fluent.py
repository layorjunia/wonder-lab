#!/usr/bin/env python3
"""Fetch the Microsoft Fluent Emoji (MIT) vector art the app shows, into img/fx/.

    python3 tools/fetch_fluent.py

tools/fluent_map.json maps each emoji the app uses to its Fluent folder name.
Writes img/fx/<codepoints>.svg and js/fx.js (FX: emoji -> file stem), so the app
shows the same crisp art on every device instead of whatever emoji font the
platform has. Anything that fails to download keeps the system emoji.
Credit: Settings > About (Microsoft Fluent Emoji, MIT).
"""
import json, os, sys, urllib.parse, urllib.request
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = 'https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets/'
OUT = os.path.join(ROOT, 'img', 'fx')


def stem(e):
    return '-'.join(f'{ord(c):x}' for c in e if c != '️')


def get(url):
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return r.read()
    except Exception:
        return None


def fetch(item):
    e, name = item
    path = os.path.join(OUT, stem(e) + '.svg')
    if os.path.exists(path) and os.path.getsize(path) > 200:
        return e, True
    slug = name.lower().replace(' ', '_')
    # people and hands have skin-tone folders: Default/Color/<name>_color_default.svg
    for sub, tail in (('Color', '_color'), ('Default/Color', '_color_default'),
                      ('Default/Color', '_default_color')):
        url = RAW + urllib.parse.quote(f'{name}/{sub}/{slug}{tail}.svg')
        data = get(url)
        if data and b'<svg' in data[:400]:
            open(path, 'wb').write(data)
            return e, True
    return e, False


def main():
    m = json.load(open(os.path.join(ROOT, 'tools', 'fluent_map.json'), encoding='utf-8'))
    with ThreadPoolExecutor(12) as ex:
        res = list(ex.map(fetch, m.items()))
    ok = {e: stem(e) for e, good in res if good}
    bad = [e for e, good in res if not good]
    js = '// Generated by tools/fetch_fluent.py. emoji -> img/fx/<stem>.svg (Microsoft Fluent Emoji, MIT)\n'
    js += 'const FX = ' + json.dumps(ok, ensure_ascii=False, separators=(',', ':')) + ';\n'
    open(os.path.join(ROOT, 'js', 'fx.js'), 'w', encoding='utf-8').write(js)
    print(f'{len(ok)} fetched, {len(bad)} failed: {" ".join(bad)}')


if __name__ == '__main__':
    main()
